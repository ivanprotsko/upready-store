def ann(items, variant="rotating"): return {"type":"announcement","variant":variant,"items":items}
def hdr(variant="inline", links=None, navCount=5):
    d={"type":"header","variant":variant,"navCount":navCount}
    if links: d["links"]=[{"label":l,"page":p} for l,p in links]
    return d
def ftr(variant, cols):
    return {"type":"footer","variant":variant,
            "columns":[{"title":t,"links":[{"label":l,"page":p} for l,p in ls]} for t,ls in cols]}
def cart(note): return {"type":"cart-drawer","source":"all","limit":2,"note":note}
def crumbs(items): return {"type":"breadcrumbs","items":[({"label":l,"page":p} if p else {"label":l}) for l,p in items]}
def head(e,t,l): return {"type":"page-head","eyebrow":e,"title":t,"lead":l}
def pager(p,c,s,t): return {"type":"pagination","pages":p,"current":c,"shown":s,"total":t}
def news(t,n,c,l): return {"type":"newsletter","title":t,"note":n,"cta":c,"legal":l}
