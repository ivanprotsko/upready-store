import { launch, shot, save, creds, PANEL, STATE } from './lib.mjs'
const { browser, ctx, page, errors } = await launch({ storage: false })
const { email, pass } = creds()
await page.goto(PANEL + '/login', { waitUntil: 'domcontentloaded', timeout: 60000 })
await page.waitForSelector('input[name=email]', { timeout: 60000 })
await page.fill('input[name=email]', email)
await page.fill('input[name=password]', pass)
await page.click('button[type=submit]')
await page.waitForTimeout(6000)
console.log('url', page.url())
console.log('body', (await page.evaluate(() => document.body.innerText)).replace(/\n{2,}/g, '\n').slice(0, 300))
await shot(page, '01-after-login')
await ctx.storageState({ path: STATE })
save('01-login.json', { url: page.url(), errors })
console.log('errors', JSON.stringify(errors.slice(0, 5)))
await browser.close()
