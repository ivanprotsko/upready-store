import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { describe, expect, it, vi } from "vitest"

import { locales } from "@i18n/config"
import { FONT_NAMES } from "@lib/theme/fonts"
import { THEME_IDS } from "@lib/theme/presets.generated"
import { BLOCKS } from "@modules/blocks/registry"

// Which blocks the backend can check props of: `propsEditable` below. A pure module.
import { PROPS_CHECKS } from "../../../../backend/src/api/tenants/home/template/validation"

import { TEMPLATE_SOURCES } from "./catalog"
import { BUTTON_STYLES, DENSITIES, PHOTO_STYLES, RADII, TEMPLATE_SCHEMA } from "./manifest"

// The registry reaches `server-only` loaders through the header and footer variants. Hoisted by vitest.
vi.mock("server-only", () => ({}))

/**
 * The backend's copy of what this side knows about templates (t-2026-10-12-33): the
 * catalogue, the block allow-list of the registry and the vocabularies a template is
 * checked against. The backend cannot import this app (no shared package, and the
 * registry imports React components), so `POST /tenants/home/template` reads this JSON.
 *
 * The test fails when the committed file is not what the storefront exports now. Write it
 * again after a change to a template, a block or a vocabulary:
 *
 *   pnpm templates:export
 */
const TARGET = fileURLToPath(
  new URL("../../../../backend/src/api/tenants/home/template/catalog.generated.json", import.meta.url)
)

function catalogExport() {
  return {
    $comment:
      "GENERATED by apps/storefront/src/lib/templates/catalog-export.test.ts (pnpm templates:export in apps/storefront). Do not edit.",
    schema: TEMPLATE_SCHEMA,
    palettes: ["default", ...THEME_IDS],
    fonts: [...FONT_NAMES],
    layers: {
      radius: [...RADII],
      buttonStyle: [...BUTTON_STYLES],
      photoStyle: [...PHOTO_STYLES],
      density: [...DENSITIES],
    },
    locales: [...locales],
    blocks: BLOCKS.map((block) => ({
      id: block.id,
      category: block.category,
      placement: block.placement,
      status: block.status,
      ...(block.setting ? { setting: block.setting } : {}),
      props: Boolean(block.parseProps),
      // A shop may change the props only where the backend holds a copy of the parser; the panel reads this.
      propsEditable: Boolean(block.parseProps) && Object.prototype.hasOwnProperty.call(PROPS_CHECKS, block.id),
    })),
    templates: TEMPLATE_SOURCES,
  }
}

const serialised = () => `${JSON.stringify(catalogExport(), null, 2)}\n`

describe("the template catalogue the backend reads", () => {
  it("is the one this storefront exports", () => {
    if (process.env.TEMPLATES_EXPORT_WRITE === "1") writeFileSync(TARGET, serialised())
    expect(readFileSync(TARGET, "utf8"), "run `pnpm templates:export` in apps/storefront").toBe(serialised())
  })
})
