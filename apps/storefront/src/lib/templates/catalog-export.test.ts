/**
 * The backend's copy of what this side knows about templates (t-2026-10-12-33): the
 * catalogue, the block allow-list of the registry and the vocabularies a template is
 * checked against. The backend cannot import this app (no shared package, and the
 * registry imports React components), so `POST /tenants/home/template` reads this JSON.
 *
 * The test fails when the committed file is not what the storefront exports now. Write it
 * again after a change to a template, a block or a vocabulary:
 *
 *   pnpm templates:export
 *
 * Laid out so that parallel block and template PRs merge without a conflict: `blocks` sorted
 * by id, one line per block; `templates` keyed in id order. Two new blocks are then separate
 * insertions in different places, unless no existing id sorts between them. Nothing reads
 * the order: the backend looks blocks and templates up by id.
 */
const TARGET = fileURLToPath(
  new URL("../../../../backend/src/api/tenants/home/template/catalog.generated.json", import.meta.url)
)

/** The generated theme sheet: the colours of every palette, per mode. */
const THEMES_CSS = fileURLToPath(new URL("../../styles/themes.css", import.meta.url))

/** The colours the panel paints a palette's swatches and a template's schematic preview in. */
const SWATCH_TOKENS = ["background", "foreground", "primary", "accent", "muted"] as const

type Swatch = Record<(typeof SWATCH_TOKENS)[number], string>

const PALETTES = ["default", ...THEME_IDS, ...LIGHT_ONLY_THEME_IDS]

/**
 * Each palette's name and colours, read from `styles/themes.css` (written by `pnpm themes:build`),
 * the blocks `[data-theme="<id>"][data-mode="<mode>"]` before the bridge. A light-only palette
 * has one block for both modes, so it gets `light` alone.
 */
function swatches() {
  const sheet = readFileSync(THEMES_CSS, "utf8").split("/* bridge")[0]
  const byPalette: Record<string, Partial<Record<"light" | "dark", Swatch>>> = {}
  for (const [, selectors, body] of Array.from(sheet.matchAll(/((?:\[data-theme="[^"]+"\]\[data-mode="(?:light|dark)"\][,\s]*)+)\{([^}]*)\}/g))) {
    const tokens = new Map(Array.from(body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g), (m) => [m[1], m[2].trim()]))
    const swatch = Object.fromEntries(SWATCH_TOKENS.map((token) => [token, tokens.get(token)])) as Swatch
    for (const [, id, mode] of Array.from(selectors.matchAll(/\[data-theme="([^"]+)"\]\[data-mode="(light|dark)"\]/g))) {
      byPalette[id] = { ...byPalette[id], [mode]: swatch }
    }
  }
  const lightOnly = new Set<string>(LIGHT_ONLY_THEME_IDS)
  return Object.fromEntries(
    PALETTES.map((id) => [
      id,
      {
        // `{ ru, en }` from the palette's theme file (P2b): the panel picks the owner's language.
        label: THEME_LABEL_TEXTS[id],
        light: byPalette[id]?.light,
        ...(lightOnly.has(id) ? {} : { dark: byPalette[id]?.dark }),
      },
    ])
  )
}

/** Plain code-unit order: the same on every Node build, unlike a locale's collation. */
const byCodeUnits = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)

/**
 * The backend's copy of every block's props parser (t-2026-10-12-33): `PROPS_CHECKS` in
 * `validation.ts` runs it, so a shop may change the props of any block that has a parser here.
 * Each block's `props.ts` and the files it imports are copied as they are, in the layout of
 * `src/modules/blocks`, with two imports pointed elsewhere: `types.ts` at a stub holding
 * `PropsResult` alone (the rest of that file is the registry's and imports React), and
 * `@i18n/config` at the catalogue's `locales`. A parser importing anything else is not pure,
 * and the export refuses it. `index.ts` lists the parsers by block id.
 */
const BLOCKS_DIR = fileURLToPath(new URL("../../modules/blocks/", import.meta.url))
const PROPS_COPY = fileURLToPath(
  new URL("../../../../backend/src/api/tenants/home/template/props.generated/", import.meta.url)
)

const GENERATED =
  "// GENERATED by apps/storefront/src/lib/templates/catalog-export.test.ts (pnpm templates:export in apps/storefront). Do not edit."

/** What a copied file may import from outside its tree, and the names it may take there. */
const STUBS: Record<string, { file: string; names: string[]; typeOnly: boolean }> = {
  [join(BLOCKS_DIR, "types.ts")]: { file: "types.ts", names: ["PropsResult"], typeOnly: true },
  "@i18n/config": { file: "locales.ts", names: ["locales"], typeOnly: false },
}

const STUB_SOURCES: Record<string, () => string> = {
  "types.ts": () => {
    const line = readFileSync(join(BLOCKS_DIR, "types.ts"), "utf8").match(/^export type PropsResult<P> = .+$/m)
    if (!line) throw new Error("src/modules/blocks/types.ts no longer declares `export type PropsResult<P> = …` on one line")
    return `${GENERATED}\n// \`PropsResult\` of src/modules/blocks/types.ts, the one name the parsers take from there.\n${line[0]}\n`
  },
  "locales.ts": () =>
    `${GENERATED}\n// \`locales\` of the storefront's i18n/config.ts, as this export writes them into the catalogue.\nimport catalog from "../catalog.generated.json"\n\nexport const locales: readonly string[] = catalog.locales\n`,
}

type Import = { specifier: string; start: number; end: number; names: string[]; typeOnly: boolean }

/** The import and export-from declarations of a file; any other way to load a module is refused. */
function importsOf(file: string, source: string): Import[] {
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const found: Import[] = []
  for (const statement of sourceFile.statements) {
    if (!(ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement))) continue
    const specifier = statement.moduleSpecifier
    if (!specifier || !ts.isStringLiteral(specifier)) continue
    const names: string[] = []
    let typeOnly = false
    if (ts.isImportDeclaration(statement)) {
      const clause = statement.importClause
      typeOnly = Boolean(clause?.isTypeOnly)
      if (clause?.name) names.push("default")
      const bindings = clause?.namedBindings
      if (bindings && ts.isNamespaceImport(bindings)) names.push("*")
      if (bindings && ts.isNamedImports(bindings)) {
        names.push(...bindings.elements.map((element) => (element.propertyName ?? element.name).text))
        if (!clause?.name && bindings.elements.length && bindings.elements.every((element) => element.isTypeOnly)) typeOnly = true
      }
    } else {
      typeOnly = statement.isTypeOnly
      names.push("*")
    }
    found.push({ specifier: specifier.text, start: specifier.getStart(sourceFile), end: specifier.getEnd(), names, typeOnly })
  }
  const loaded = ts.preProcessFile(source, true, true).importedFiles.length
  if (loaded !== found.length) throw new Error(`${file}: loads a module other than by an import declaration`)
  return found
}

/** A relative import as a file of the tree: `<path>.ts` or `<path>/index.ts`. */
function resolveImport(from: string, specifier: string): string {
  const base = resolve(dirname(from), specifier)
  const file = [`${base}.ts`, join(base, "index.ts")].find((candidate) => existsSync(candidate))
  if (!file) throw new Error(`${from}: ${specifier} is not a .ts file`)
  return file
}

const posixPath = (path: string) => path.split(sep).join("/")

/** `./x` rather than `x` for a relative specifier. */
const dotted = (path: string) => (path.startsWith(".") ? path : `./${path}`)

type PropsCopy = { files: Record<string, string>; parsers: ReadonlySet<string> }

let propsCopyOnce: Promise<PropsCopy> | null = null

/** The files of `props.generated/`, by path under it, and the blocks whose parser they hold. */
function propsCopy(): Promise<PropsCopy> {
  propsCopyOnce ??= (async () => {
    const files: Record<string, string> = {}
    const pending: string[] = []
    const entries: { id: string; name: string; from: string }[] = []

    for (const block of [...BLOCKS].sort((a, b) => byCodeUnits(a.id, b.id))) {
      if (!block.parseProps) continue
      const file = join(BLOCKS_DIR, block.id, "props.ts")
      const exported = existsSync(file) ? ((await import(/* @vite-ignore */ file)) as Record<string, unknown>) : {}
      const name = Object.keys(exported).find((key) => exported[key] === block.parseProps)
      if (!name) throw new Error(`${block.id}: parseProps must be an export of its own props.ts, which the backend copies`)
      entries.push({ id: block.id, name, from: dotted(posixPath(relative(BLOCKS_DIR, file)).replace(/\.ts$/, "")) })
      pending.push(file)
    }

    const stubs = new Set<string>()
    for (let file = pending.pop(); file; file = pending.pop()) {
      const path = posixPath(relative(BLOCKS_DIR, file))
      if (path in files) continue
      let source = readFileSync(file, "utf8")
      const rewrites: { start: number; end: number; to: string }[] = []
      for (const one of importsOf(path, source)) {
        const target = one.specifier.startsWith(".") ? resolveImport(file, one.specifier) : one.specifier
        const stub = STUBS[target]
        if (stub) {
          const stranger = one.names.filter((name) => !stub.names.includes(name))
          if (stranger.length || (stub.typeOnly && !one.typeOnly)) {
            throw new Error(`${path}: takes ${one.names.join(", ")} from ${one.specifier}; the backend copy has only ${stub.names.join(", ")}`)
          }
          stubs.add(stub.file)
          const to = dotted(posix.relative(posix.dirname(path), stub.file.replace(/\.ts$/, "")))
          if (to !== one.specifier) rewrites.push({ start: one.start, end: one.end, to: JSON.stringify(to) })
        } else if (!one.specifier.startsWith(".") || relative(BLOCKS_DIR, target).startsWith("..")) {
          throw new Error(`${path}: imports ${one.specifier}; a props parser may import only src/modules/blocks and @i18n/config`)
        } else {
          pending.push(target)
        }
      }
      for (const { start, end, to } of rewrites.sort((a, b) => b.start - a.start)) {
        source = source.slice(0, start) + to + source.slice(end)
      }
      files[path] = `${GENERATED}\n// Copied from apps/storefront/src/modules/blocks/${path}.\n${source}`
    }
    for (const stub of Array.from(stubs)) files[stub] = STUB_SOURCES[stub]()

    const taken = new Map<string, number>()
    const imports = entries.map((entry) => {
      const seen = taken.get(entry.name) ?? 0
      taken.set(entry.name, seen + 1)
      const local = seen ? `${entry.name}${seen + 1}` : entry.name
      return { ...entry, local, line: `import { ${entry.name === local ? local : `${entry.name} as ${local}`} } from "${entry.from}"` }
    })
    files["index.ts"] = [
      GENERATED,
      "// Every block's props parser, by block id: the `parseProps` of each block that has one.",
      'import type { PropsResult } from "./types"',
      ...imports.map((entry) => entry.line),
      "",
      "export const PROPS_PARSERS: Record<string, (input: unknown) => PropsResult<unknown>> = {",
      ...imports.map((entry) => `  ${JSON.stringify(entry.id)}: ${entry.local},`),
      "}",
      "",
    ].join("\n")
    if (!stubs.has("types.ts")) files["types.ts"] = STUB_SOURCES["types.ts"]()

    const sorted = Object.fromEntries(Object.entries(files).sort(([a], [b]) => byCodeUnits(a, b)))
    return { files: sorted, parsers: new Set(entries.map((entry) => entry.id)) }
  })()
  return propsCopyOnce
}

/** Every file under `dir`, by its path there; none when it is missing. */
function filesUnder(dir: string): Record<string, string> {
  if (!existsSync(dir)) return {}
  const paths = (readdirSync(dir, { recursive: true }) as string[]).map(posixPath).sort(byCodeUnits)
  return Object.fromEntries(
    paths.filter((path) => statSync(join(dir, path)).isFile()).map((path) => [path, readFileSync(join(dir, path), "utf8")])
  )
}

function catalogExport(copied: ReadonlySet<string>) {
  return {
    $comment:
      "GENERATED by apps/storefront/src/lib/templates/catalog-export.test.ts (pnpm templates:export in apps/storefront). Do not edit.",
    schema: TEMPLATE_SCHEMA,
    palettes: PALETTES,
    // These have no dark mode: a template on one of them asks for settings.defaultMode "light".
    lightOnlyPalettes: [...LIGHT_ONLY_THEME_IDS],
    // The panel's swatches and schematic previews (t-2026-10-12-33 P2), from the generated theme sheet.
    swatches: swatches(),
    fonts: [...FONT_NAMES],
    layers: {
      radius: [...RADII],
      buttonStyle: [...BUTTON_STYLES],
      photoStyle: [...PHOTO_STYLES],
      density: [...DENSITIES],
    },
    // The gap between home sections at each density, in px: the panel's schematic draws its gaps in this proportion.
    sectionGapPx: SECTION_GAP_PX,
    locales: [...locales],
    blocks: [...BLOCKS]
      .sort((a, b) => byCodeUnits(a.id, b.id))
      .map((block) => ({
        id: block.id,
        category: block.category,
        placement: block.placement,
        status: block.status,
        ...(block.setting ? { setting: block.setting } : {}),
        props: Boolean(block.parseProps),
        // A shop may change the props only where the backend holds a copy of the parser; the panel reads this.
        propsEditable: copied.has(block.id),
      })),
    templates: Object.fromEntries(Object.entries(TEMPLATE_SOURCES).sort(([a], [b]) => byCodeUnits(a, b))),
  }
}

/** `JSON.stringify(…, null, 2)` with one change: each entry of `blocks` on a line of its own. */
function serialised(copied: ReadonlySet<string>) {
  const entries = Object.entries(catalogExport(copied)).map(([key, value]) => {
    const body =
      key === "blocks"
        ? `[\n${(value as unknown[]).map((block) => `    ${JSON.stringify(block)}`).join(",\n")}\n  ]`
        : JSON.stringify(value, null, 2).replace(/\n/g, "\n  ")
    return `  ${JSON.stringify(key)}: ${body}`
  })
  return `{\n${entries.join(",\n")}\n}\n`
}

describe("the template catalogue the backend reads", () => {
  it("is the one this storefront exports", async () => {
    const expected = serialised((await propsCopy()).parsers)
    if (process.env.TEMPLATES_EXPORT_WRITE === "1") writeFileSync(TARGET, expected)
    expect(readFileSync(TARGET, "utf8"), "run `pnpm templates:export` in apps/storefront").toBe(expected)
  })

  it("comes with the backend's copy of every props parser, the one this storefront exports", async () => {
    const { files } = await propsCopy()
    if (process.env.TEMPLATES_EXPORT_WRITE === "1") {
      for (const [path, body] of Object.entries(files)) {
        mkdirSync(dirname(join(PROPS_COPY, path)), { recursive: true })
        writeFileSync(join(PROPS_COPY, path), body)
      }
      // A file the export wrote once and writes no more: a block that lost its parser, a helper no parser imports.
      for (const [path, body] of Object.entries(filesUnder(PROPS_COPY))) {
        if (!(path in files) && body.startsWith(GENERATED)) rmSync(join(PROPS_COPY, path))
      }
    }
    expect(filesUnder(PROPS_COPY), "run `pnpm templates:export` in apps/storefront").toEqual(files)
  })

  it("copies a parser for every block that has one", async () => {
    const { parsers } = await propsCopy()
    expect(Array.from(parsers)).toEqual(BLOCKS.filter((block) => block.parseProps).map((block) => block.id).sort(byCodeUnits))
  })

  // P2b: the panel names a palette in the owner's language; the words live in the theme's own file.
  it("names every palette in Russian and English, the default one «Стандартная»", () => {
    for (const id of PALETTES) {
      const label = THEME_LABEL_TEXTS[id] as Record<string, string>
      expect(label, id).toMatchObject({ ru: expect.stringMatching(/[а-яё]/i), en: expect.any(String) })
      expect(label.en, `${id}: the English label stays THEME_LABELS`).toBe(THEME_LABELS[id])
    }
    expect(THEME_LABEL_TEXTS.default).toEqual({ ru: "Стандартная", en: "Medusa default" })
    expect(THEME_LABEL_TEXTS.medusa).toEqual(THEME_LABEL_TEXTS.default)
  })

  it("gives every palette its name and five colours, both modes unless the palette is light-only", () => {
    const all = swatches()
    for (const id of PALETTES) {
      const entry = all[id]
      expect(entry.label, id).toEqual(THEME_LABEL_TEXTS[id])
      const modes = (LIGHT_ONLY_THEME_IDS as readonly string[]).includes(id) ? ["light"] : ["light", "dark"]
      expect(Object.keys(entry).filter((key) => key !== "label"), id).toEqual(modes)
      for (const mode of modes) {
        const swatch = entry[mode as "light" | "dark"] as Swatch
        for (const token of SWATCH_TOKENS) expect(swatch[token], `${id} ${mode} --${token}`).toMatch(/^(#[0-9a-f]{6}|rgba?\([\d.,\s]+\))$/i)
      }
    }
  })
})
