import { HttpTypes } from "@medusajs/types"
import { useMemo } from "react"
import { useTranslation } from "react-i18next"

import { createDataTableColumnHelper } from "@medusajs/ui"
import { DataTableStatusCell } from "../../components/data-table-status-cell/data-table-status-cell"
import { useDataTableDateColumns } from "../general/use-data-table-date-columns"

const columnHelper = createDataTableColumnHelper<HttpTypes.AdminSalesChannel>()

export const useSalesChannelTableColumns = () => {
  const { t } = useTranslation()
  const dateColumns = useDataTableDateColumns<HttpTypes.AdminSalesChannel>()

  // `GET /tenants/sales-channels` returns only the tenant's own channel
  // (`hooks/api/sales-channels.tsx`), so this table is always exactly one
  // row here. Its "description" ("Sales channel of tenant \"cherkashino\"")
  // is generated by the backend at tenant creation as internal cross-tenant
  // bookkeeping (`create-tenant/index.ts`), never meant for a shop owner's
  // screen — and with one row it identifies nothing besides "name" already
  // does. Dropped rather than translated: a raw enum/internal string reaches
  // the screen only through a real label map (rule 18e), and there is no
  // per-owner label to map this one to.
  return useMemo(
    () => [
      columnHelper.accessor("name", {
        header: () => t("fields.name"),
        enableSorting: true,
        sortLabel: t("fields.name"),
        sortAscLabel: t("filters.sorting.alphabeticallyAsc"),
        sortDescLabel: t("filters.sorting.alphabeticallyDesc"),
      }),
      columnHelper.accessor("is_disabled", {
        header: () => t("fields.status"),
        enableSorting: true,
        sortLabel: t("fields.status"),
        sortAscLabel: t("filters.sorting.alphabeticallyAsc"),
        sortDescLabel: t("filters.sorting.alphabeticallyDesc"),
        cell: ({ getValue }) => {
          const value = getValue()
          return (
            <DataTableStatusCell color={value ? "grey" : "green"}>
              {value ? t("general.disabled") : t("general.enabled")}
            </DataTableStatusCell>
          )
        },
      }),
      ...dateColumns,
    ],
    [t, dateColumns]
  )
}
