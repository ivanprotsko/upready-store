/**
 * funnel.ts — единственное место, где страница знает адреса воронки.
 *
 * Концепция (`artifacts/docs/2026-09-13-homepage-concept.md` §2): один призыв
 * «Создать магазин» ведёт в сценарий 3 воронки, а кнопки тарифов входят в тот
 * же сценарий с уже выбранным тарифом и сразу ведут в кассу.
 *
 * База адреса берётся из `VITE_FUNNEL_BASE_URL`. Переменной нет — остаётся
 * относительный путь `/start/…`: он работает и на dev-сервере, и когда воронка
 * стоит на том же домене, что страница. Пустая строка переменной — это НЕ
 * значение (правило 20a), она трактуется как «база не задана».
 */

export interface FunnelScenario {
  /** Путь с параметрами сценария, всегда начинается с `/start/`. */
  path: string;
  /** Человеческая расшифровка — уезжает в `title` ссылки. */
  title: string;
}

const rawBase: unknown = import.meta.env.VITE_FUNNEL_BASE_URL;

/** База без хвостового слэша либо пустая строка. */
export const FUNNEL_BASE: string =
  typeof rawBase === "string" && rawBase.trim() !== ""
    ? rawBase.trim().replace(/\/+$/, "")
    : "";

/** Кнопка «Создать магазин»: шапка, герой, блок «Почему сейчас», финал. */
export const HERO_SCENARIO: FunnelScenario = {
  path: "/start/plan?f=3",
  title: "Сценарий 3 · выбор тарифа, дальше касса",
};

/**
 * Планы от 2026-09-14 (t-2026-09-14-01): Новичок · Профи · Мастер. Ключи
 * free/pro/ultra переживают переименования тарифов и не меняются вместе с
 * ними: за ночь имена сменились дважды (Бесплатный/Бизнес/Про →
 * Бесплатный/Про/Ультра → Новичок/Профи/Мастер), а адрес воронки один.
 *
 * Параметр `p=` переименован вместе с планом: `store-free`, `store-pro`,
 * `store-ultra` — идентификатор совпадает с названием тарифа, и один словарь
 * работает на странице, в кассе и в инвентаре фич.
 *
 * Почему не оставили старые значения. Касса воронки
 * (`apps/storefront/src/lib/demo/catalog.ts`, ветка feat/abstract-datasets)
 * знает store-start 4 900 ₽, store-business 9 900 ₽ и store-pro 19 900 ₽
 * «разово» — ни одна из трёх цен не совпадает ни с одной ценой этой страницы
 * (0 / 699 / 4 499 ₽ в месяц), то есть сохранять «рабочее» соответствие было
 * нечего. При старых значениях два тарифа из трёх молча показывали бы в кассе
 * чужую цену; при новых незнакомые кассе `store-free` и `store-ultra` уходят в
 * `resolvePlan` → `null`, то есть расхождение видно, а не подставляется тихо
 * (правило 20a). Совпадает только `store-pro`, у которого в кассе пока стоит
 * старая цена 19 900 ₽. Кассу приводят к этим трём планам отдельной задачей —
 * инвентарь фич §5.
 */
export const PLAN_SCENARIOS: Record<"free" | "pro" | "ultra", FunnelScenario> = {
  free: {
    path: "/start/pay?f=3&s=store&p=store-free",
    title: "Сценарий 3 · тариф «Новичок» выбран, дальше подтверждение и мастер",
  },
  pro: {
    path: "/start/pay?f=3&s=store&p=store-pro",
    title: "Сценарий 3 · тариф «Профи» 699 ₽ в месяц выбран, дальше касса",
  },
  ultra: {
    path: "/start/pay?f=3&s=store&p=store-ultra",
    title: "Сценарий 3 · тариф «Мастер» 4 499 ₽ в месяц выбран, дальше касса",
  },
};

/** Адрес для href. Каждый CTA страницы проходит через эту функцию. */
export function funnelUrl(scenario: FunnelScenario): string {
  return `${FUNNEL_BASE}${scenario.path}`;
}
