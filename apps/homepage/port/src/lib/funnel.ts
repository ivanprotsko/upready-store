/**
 * funnel.ts — единственное место, где страница знает адреса воронки.
 *
 * Решение Ивана от 2026-09-14: страница ведёт в ДВА разных места, и ветка
 * выбирается тарифом.
 *
 *   • «Создать магазин» (шапка, герой, «Почему сейчас», финал и карточка
 *     бесплатного тарифа) → мастер онбординга `/start/onboarding`: имя
 *     магазина, доступ, оформление — и в конце магазин уже создан, с готовым
 *     абстрактным каталогом.
 *   • «Попробовать бесплатно» на платных тарифах → телеграм-бот
 *     `https://t.me/<бот>?start=plan_<номер>`; оплату принимает бот, а не
 *     страница.
 *
 * Прежний сценарий 3 (`/start/plan` → `/start/pay` → касса storefront) с этой
 * страницы больше не вызывается: платит бот. Поэтому словаря `PLAN_SCENARIOS`
 * здесь нет — он адресовал кассу, к которой у страницы не осталось кнопок.
 *
 * База адреса мастера берётся из `VITE_FUNNEL_BASE_URL`. Переменной нет —
 * остаётся относительный путь `/start/…`: он работает и на dev-сервере, и
 * когда воронка стоит на том же домене, что страница. Пустая строка
 * переменной — это НЕ значение (правило 20a), она трактуется как «база не
 * задана».
 */

export interface FunnelScenario {
  /** Путь с параметрами сценария, всегда начинается с `/start/`. */
  path: string;
  /** Человеческая расшифровка — уезжает в `title` ссылки. */
  title: string;
}

const rawBase: unknown = import.meta.env.VITE_FUNNEL_BASE_URL;

/** База без хвостового слэша либо пустая строка. */
export const FUNNEL_BASE: string =
  typeof rawBase === "string" && rawBase.trim() !== ""
    ? rawBase.trim().replace(/\/+$/, "")
    : "";

/**
 * Мастер создания магазина — три шага (магазин · доступ · оформление), в конце
 * витрина уже отвечает по своему адресу, каталог засеян абстрактным набором.
 * Живёт в storefront линии MT (`apps/storefront/src/app/start/onboarding`,
 * ветка feat/abstract-datasets), поэтому адрес и берёт базу из переменной.
 */
export const ONBOARDING_SCENARIO: FunnelScenario = {
  path: "/start/onboarding",
  title: "Мастер: имя магазина, доступ, оформление — магазин создаётся сразу",
};

const rawBot: unknown = import.meta.env.VITE_TELEGRAM_BOT;

/** Имя бота без `@`. Переменной нет — бот upready-store из `.env` Ивана. */
export const TELEGRAM_BOT: string =
  typeof rawBot === "string" && rawBot.trim() !== ""
    ? rawBot.trim().replace(/^@/, "")
    : "upreadystore_bot";

/**
 * Диплинк тарифа в бота — формат задан Иваном дословно: `?start=plan_1`,
 * `plan_2`, `plan_3`.
 *
 * Номер — это ПОРЯДОК КАРТОЧКИ на странице (1 — первый тариф), а не ключ
 * плана. Так сделано намеренно: имена и ключи тарифов за сутки сменились
 * дважды (Бесплатный/Бизнес/Про → Бесплатный/Про/Ультра → Новичок/Профи/
 * Мастер), а порядок карточек — от дешёвой к дорогой — не менялся ни разу, и
 * боту достаточно знать, какой из трёх выбран.
 */
export function telegramPlanUrl(planNumber: number): string {
  return `https://t.me/${TELEGRAM_BOT}?start=plan_${planNumber}`;
}

/** Адрес для href. Каждый CTA страницы проходит через эту функцию. */
export function funnelUrl(scenario: FunnelScenario): string {
  return `${FUNNEL_BASE}${scenario.path}`;
}
