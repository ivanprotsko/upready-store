/** Ключи планов — они же ключи сценариев воронки в `src/lib/funnel.ts`. */
export type PlanKey = "free" | "pro" | "ultra";

/**
 * Значение одной строки карточки. `note` — маркер сноски, который рисуется
 * верхним индексом рядом со значением; пустая строка означает «сноски нет»
 * (пустое значение — это НЕ маркер, правило 20a).
 */
export interface PlanValue {
  text: string;
  note: string;
}

/** Пять значений в одном порядке у всех планов. */
export type PlanValues = readonly [PlanValue, PlanValue, PlanValue, PlanValue, PlanValue];

/** Пробный период плана. `null` — пробного периода у плана нет. */
export interface PlanTrial {
  /** Крупная строка: сколько бесплатно. */
  lead: string;
  /** Условие целиком: когда период стартует и что будет по окончании. */
  text: string;
}

export interface Plan {
  scenario: PlanKey;
  name: string;
  /** Крупная цифра. */
  price: string;
  /** Подпись рядом с ценой. */
  period: string;
  /** Вторая строка цены — годовая оплата; пустая, если не задана. */
  annual: string;
  /** Значения строк карточки, в одном порядке у всех планов. */
  values: PlanValues;
  trial: PlanTrial | null;
  cta: string;
}

const plain = (text: string): PlanValue => ({ text, note: "" });

