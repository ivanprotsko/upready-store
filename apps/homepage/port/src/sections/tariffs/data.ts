// «Тарифы» — три плана по приказу Ивана от 2026-09-14 (t-2026-09-14-01),
// правка того же дня: Бесплатный · Про · Ультра, переключатель периода оплаты,
// значения с пунктирным подчёркиванием и подсказкой по наведению.
//
// Подписей строк слева нет (приказ §3): в карточке стоят только значения, и
// каждое читается само по себе — «15 товаров», а не «15». Порядок значений
// одинаков во всех трёх карточках (каталог · дизайн · поддержка · языки ·
// Telegram Mini App), поэтому карточки читаются как сравнение: строки стоят на
// одной высоте, и глаз сравнивает их по позиции. Разделительных линий между
// строками больше нет (правка §4) — сравнение держится на позиции, не на сетке.
//
// Сносок под карточками тоже больше нет (правка §6): то, что было сноской,
// живёт в подсказке того значения, к которому относится. Верхний индекс рядом
// со значением остался как знак «здесь есть условие» — их ровно три, по одному
// на карточку: ¹ Telegram Mini App, ² пробный период «Про», ³ каталог «Ультра».
//
// Годовая цена известна только у «Про» (5 499 ₽). Годовая цена «Ультра» не
// назначена — выдуманной цифры на странице нет (правило 17a), в годовом режиме
// у «Ультра» стоит месячная цена и честная строка о том, что года ещё нет.
//
// Касса воронки (`apps/storefront/src/lib/demo/catalog.ts`, ветка
// feat/abstract-datasets) периодов оплаты не знает вовсе — переключатель пока
// живёт только на странице, параметры `p=` не меняются. Решение по `p=` — в
// `src/lib/funnel.ts` и в NOTES.md.

export const EYEBROW = "Тарифы";

