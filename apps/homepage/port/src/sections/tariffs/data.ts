// «Тарифы» — три плана по приказу Ивана от 2026-09-14 (t-2026-09-14-01):
// Бесплатный · Про 699 ₽/мес (5 499 ₽/год, −35 %) · Ультра 4 499 ₽/мес.
// Прежний «Бизнес» стал «Про», прежний «Про» — «Ультра»; цены и периоды те же,
// вместе с названиями переименованы ключи сценариев воронки и подписи кнопок.
//
// Подписей строк слева больше нет (приказ §3): в карточке стоят только
// значения, и каждое читается само по себе — «15 товаров», а не «15». Порядок
// значений одинаков во всех трёх карточках (каталог · дизайн · поддержка ·
// языки · Telegram Mini App), поэтому карточки по-прежнему читаются как
// сравнение: строки стоят на одной высоте, и глаз сравнивает их по позиции.
//
// Допущения, не названные в приказе (инвентарь фич §2, решает Иван):
// языки витрины в «Бесплатном» и «Про» — один; годовая цена «Ультра» не
// задана, поэтому второй строки цены у неё нет.
//
// Касса воронки (`apps/storefront/src/lib/demo/catalog.ts`, ветка
// feat/abstract-datasets) знает старые планы store-start 4 900 / store-business
// 9 900 / store-pro 19 900 «разово» — ни одна из этих цен не совпадает ни с
// одной ценой этой страницы. Решение по параметрам `p=` — в `src/lib/funnel.ts`
// и в NOTES.md.

