/** Ключи планов — они же ключи сценариев воронки в `src/lib/funnel.ts`. */
export type PlanKey = "free" | "pro" | "ultra";

/** Период оплаты, который выбран переключателем над карточками. */
export type BillingPeriod = "annual" | "monthly";

export const BILLING_OPTIONS: readonly { key: BillingPeriod; label: string }[] = [
  { key: "annual", label: "Оплата за год" },
  { key: "monthly", label: "За месяц" },
];

export const DEFAULT_BILLING: BillingPeriod = "annual";

/**
 * Значение одной строки карточки.
 * `hint` — подсказка по наведению: что это свойство означает; пустой она не
 * бывает, подчёркивание без подсказки обмануло бы курсор.
 * `note` — верхний индекс рядом со значением; пустая строка означает «индекса
 * нет» (пустое значение — это НЕ маркер, правило 20a).
 */
export interface PlanValue {
  text: string;
  hint: string;
  note: string;
}

/** Пять значений в одном порядке у всех планов. */
export type PlanValues = readonly [PlanValue, PlanValue, PlanValue, PlanValue, PlanValue];

/** Пробный период плана. `null` — пробного периода у плана нет. */
export interface PlanTrial {
  /** Плашка в правом верхнем углу карточки. */
  lead: string;
  /** Верхний индекс рядом с плашкой. */
  note: string;
  /** Условие целиком — оно и есть подсказка по наведению. */
  text: string;
}

/** Цена одного плана в одном периоде оплаты. */
export interface PlanPrice {
  /** Крупная строка. */
  amount: string;
  /** Подпись рядом с крупной строкой. */
  period: string;
  /** Строка под ценой; пустая, если сказать нечего. */
  note: string;
}

export interface Plan {
  scenario: PlanKey;
  name: string;
  prices: Record<BillingPeriod, PlanPrice>;
  /** Значения строк карточки, в одном порядке у всех планов. */
  values: PlanValues;
  trial: PlanTrial | null;
  cta: string;
}

