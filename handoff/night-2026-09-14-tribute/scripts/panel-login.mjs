import { chromium } from "/opt/homebrew/lib/node_modules/playwright/index.mjs";
const ART = "/Users/ivanprotsko/upready/projects/upready-store/handoff/night-2026-09-14-tribute/artifacts";
const email = "commerce-1106@upready.dev", pass = "NightAccept2026!";
const errs = [], bad = [];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: "ru-RU" });
const p = await ctx.newPage();
p.on("console", m => { if (m.type()==="error") errs.push(m.text().slice(0,200)); });
p.on("response", r => { if (r.status()>=400) bad.push(`${r.status()} ${r.request().method()} ${r.url().slice(0,140)}`); });
await p.goto("https://panel-store.upready.dev/", { waitUntil: "networkidle", timeout: 60000 });
console.log("URL after load:", p.url());
await p.screenshot({ path: `${ART}/commerce-05-panel-login.png`, fullPage: true });
const ins = await p.$$eval("input", els => els.map(e=>({ty:e.type,name:e.name,id:e.id,ph:e.placeholder})));
console.log("LOGIN INPUTS:", JSON.stringify(ins));
await p.fill('input[type=email], input[name=email]', email);
await p.fill('input[type=password]', pass);
await p.click('button[type=submit]');
await p.waitForTimeout(4000);
console.log("URL after login:", p.url());
await p.screenshot({ path: `${ART}/commerce-06-panel-home.png`, fullPage: true });
const nav = await p.$$eval("nav a, aside a", els => els.map(e=>`${e.getAttribute("href")} :: ${(e.innerText||"").trim().slice(0,40)}`));
console.log("NAV:", JSON.stringify([...new Set(nav)], null, 1));
console.log("BODY:", (await p.innerText("body")).slice(0,1200));
await ctx.storageState({ path: `${ART}/../scripts/panel-state.json` });
console.log("ERRS:", JSON.stringify(errs)); console.log("BAD:", JSON.stringify(bad));
await b.close();
