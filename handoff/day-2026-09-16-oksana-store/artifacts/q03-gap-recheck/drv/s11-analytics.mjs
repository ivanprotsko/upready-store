const t = (await page.evaluate(() => document.body.innerText)).replace(/\n{2,}/g, '\n');
console.log(t.slice(t.indexOf('Продажи'), t.indexOf('Продажи') + 700));
await page.screenshot({ path: path.join(ROOT, 'shots', 's11-panel-overview-sales-1280x900.png') });
fs.writeFileSync(path.join(ROOT, 'raw', 's11-analytics.txt'), t);
await browser.close();
