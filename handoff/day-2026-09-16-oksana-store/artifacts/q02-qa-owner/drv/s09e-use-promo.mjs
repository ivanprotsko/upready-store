import { launch, shot, timedGoto, save, SHOP } from './lib.mjs';
const { browser, page, errors } = await launch({storage:false});
const nav = await timedGoto(page, SHOP + '/ru/products/svechi-asd-s-chesnokom-10-sht-cherkashino', {waitUntil:'load'});
await page.waitForTimeout(5000);
await page.locator('button:has-text("В корзину")').first().click();
await page.waitForTimeout(6000);
await shot(page,'s09-added-to-cart');
const n2 = await timedGoto(page, SHOP + '/ru/cart', {waitUntil:'load'}); await page.waitForTimeout(6000);
console.log('cart status', n2.status, 'ms', n2.ms);
const t = (await page.evaluate(()=>document.body.innerText)).replace(/\n{2,}/g,'\n');
console.log('CART:\n'+t.slice(0,1500));
await shot(page,'s09-cart');
const inputs = await page.$$eval('input', e=>e.map(x=>({n:x.name,ph:x.placeholder,t:x.type})));
console.log('inputs', JSON.stringify(inputs));
const btns = await page.$$eval('button', e=>[...new Set(e.map(x=>(x.innerText||'').trim()))].filter(Boolean));
console.log('buttons', JSON.stringify(btns));
save('s09-cart.json',{n2,t:t.slice(0,3000),inputs,btns,errors});
console.log('errors', JSON.stringify(errors.slice(0,4)));
await browser.close();
