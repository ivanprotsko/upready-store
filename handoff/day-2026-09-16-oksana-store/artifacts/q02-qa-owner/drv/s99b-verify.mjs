r.panelHasTestProduct = /ТЕСТ QA/.test(await page.evaluate(()=>document.body.innerText));
await timedGoto(page, PANEL+'/promotions'); await page.waitForTimeout(7000);
r.panelHasPromo = /QATESTQ02/.test(await page.evaluate(()=>document.body.innerText));
await timedGoto(page, PANEL+'/pages'); await page.waitForTimeout(7000);
const pt = await page.evaluate(()=>document.body.innerText);
r.pageRow = (pt.slice(pt.indexOf('Тестовая страница QA'), pt.indexOf('Тестовая страница QA')+150)||'').replace(/\n+/g,' | ');
